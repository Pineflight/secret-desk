import { execFileSync } from "node:child_process";
import { chmod, mkdir, mkdtemp, readFile, realpath, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { delimiter, join } from "node:path";
import { parseEnvText } from "@secret-desk/core";
import { createRuntime, exportEnv } from "@secret-desk/runtime";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { main, orderTemplatesByRefs } from "../src/index.js";

const MADE_UP_ANON = ["made", "up", "anon", "value"].join("-");

const INVENTORY = `version: 1
secrets: []
envTemplates:
  - id: intake-dev
    repo: intake
    stage: dev
    entries:
      - { key: LEAD_INTAKE_TOKENS, from: { type: ref, template: landing-dev, key: LEAD_INTAKE_TOKEN } }
      - { key: SUPABASE_ANON_KEY, from: { type: command, command: supabase-status, key: ANON_KEY } }
      - { key: MAPS_KEY, from: { type: prompt, optional: true } }
  - id: landing-dev
    repo: landing
    stage: dev
    file: apps/web/.env.local
    entries:
      - { key: LEAD_INTAKE_TOKEN, from: { type: generate, kind: hex, bytes: 16 } }
  - id: needs-dev
    repo: needs
    stage: dev
    entries:
      - { key: STRIPE_SECRET_KEY, from: { type: prompt } }
`;

async function gitRepo(path: string, ignore: string | null): Promise<void> {
  await mkdir(path, { recursive: true });
  execFileSync("git", ["init", "-q"], { cwd: path });
  if (ignore !== null) await writeFile(join(path, ".gitignore"), ignore);
}

async function setup() {
  const dir = await realpath(await mkdtemp(join(tmpdir(), "sd-cli-tpl-")));
  await writeFile(join(dir, "inventory.yaml"), INVENTORY);
  const intake = join(dir, "repos", "intake");
  const landing = join(dir, "repos", "landing");
  await gitRepo(intake, null);
  await gitRepo(landing, ".env.local\n");
  await mkdir(join(intake, "supabase"), { recursive: true });
  await writeFile(join(intake, "supabase", "config.toml"), "");
  await writeFile(join(dir, "links.json"), JSON.stringify({ version: 1, links: { intake, landing } }));
  const config = join(dir, "secret-desk.config.yaml");
  await writeFile(
    config,
    `inventory: ./inventory.yaml\nlinksFile: ${JSON.stringify(join(dir, "links.json"))}\nvault: { enabled: false }\ngithub:\n  owner: acme\n  auth: { type: pat, source: { type: env, name: SD_CLI_TPL } }\npolicy:\n  envRoots: [${JSON.stringify(dir)}]\n`,
  );
  process.env.SD_CLI_TPL = "x";
  // Fake supabase CLI: only answers inside a folder with supabase/config.toml (the linked repository).
  const bin = join(dir, "bin");
  await mkdir(bin);
  await writeFile(join(bin, "supabase"), `#!/bin/sh\n[ -f supabase/config.toml ] || exit 7\necho 'API_URL="http://127.0.0.1:54321"'\necho 'ANON_KEY="${MADE_UP_ANON}"'\n`);
  await chmod(join(bin, "supabase"), 0o755);
  const out: string[] = [];
  const err: string[] = [];
  return { dir, config, intake, landing, bin, out, err, io: { out: (l: string) => out.push(l), err: (l: string) => err.push(l) } };
}

let oldPath: string | undefined;
beforeEach(() => {
  oldPath = process.env.PATH;
});
afterEach(() => {
  process.env.PATH = oldPath;
});

describe.skipIf(process.platform === "win32")("secret-desk env export (template mode)", () => {
  it("writes each template to <linked folder>/<file>, shares the ref value, runs the command in the repository", async () => {
    const t = await setup();
    process.env.PATH = `${t.bin}${delimiter}${oldPath ?? ""}`;
    const code = await main(["env", "export", "--from-template", "--config", t.config, "--repo", "intake", "--repo", "landing"], t.io);
    expect(t.err.join("\n")).not.toMatch(/^Error/m);
    expect(code).toBe(0);
    const landingFile = join(t.landing, "apps", "web", ".env.local");
    const intakeFile = join(t.intake, ".env.local");
    const landingEnv = parseEnvText(await readFile(landingFile, "utf8"));
    const intakeText = await readFile(intakeFile, "utf8");
    const intakeEnv = parseEnvText(intakeText);
    const token = landingEnv.get("LEAD_INTAKE_TOKEN")!;
    expect(token).toMatch(/^[0-9a-f]{32}$/);
    expect(intakeEnv.get("LEAD_INTAKE_TOKENS")).toBe(token);
    expect(intakeEnv.get("SUPABASE_ANON_KEY")).toBe(MADE_UP_ANON);
    expect(intakeText).toContain("# MAPS_KEY= (optional, not set)");
    expect(intakeText.startsWith("# Generated by secret-desk on ")).toBe(true);
    if (process.platform !== "win32") expect((await stat(intakeFile)).mode & 0o777).toBe(0o600);
    // landing comes first (intake refers to it), English output, values never on the terminal
    expect(t.out[0]).toBe(`written: ${landingFile} (1 of 1 keys set, mode 600)`);
    expect(t.out).toContain(`written: ${intakeFile} (2 of 3 keys set, mode 600)`);
    expect(t.out).toContain("  left empty: MAPS_KEY");
    // the git-ignore check runs in the target repository: intake has no .gitignore
    expect(t.err).toContain("  warning: The file is not ignored by Git. Add it to .gitignore before anything is committed.");
    expect(t.err.join("\n")).not.toContain("landing");
    const terminal = [...t.out, ...t.err].join("\n");
    expect(terminal).not.toContain(token);
    expect(terminal).not.toContain(MADE_UP_ANON);
  });

  it("a ref reads the file the other template produced earlier", async () => {
    const t = await setup();
    expect(await main(["env", "export", "--from-template", "--config", t.config, "--repo", "landing"], t.io)).toBe(0);
    const token = parseEnvText(await readFile(join(t.landing, "apps", "web", ".env.local"), "utf8")).get("LEAD_INTAKE_TOKEN");
    expect(await main(["env", "export", "--from-template", "--no-commands", "--config", t.config, "--repo", "intake"], t.io)).toBe(0);
    const intakeText = await readFile(join(t.intake, ".env.local"), "utf8");
    expect(parseEnvText(intakeText).get("LEAD_INTAKE_TOKENS")).toBe(token);
    expect(intakeText).toContain("# SUPABASE_ANON_KEY= (filled by the CLI from supabase-status)");
  });

  it("errors are English and name what to do, without values", async () => {
    const t = await setup();
    expect(await main(["env", "export", "--from-template", "--no-commands", "--config", t.config, "--repo", "intake"], t.io)).toBe(2);
    expect(t.err.join("\n")).toBe("Error: LEAD_INTAKE_TOKENS: No value for LEAD_INTAKE_TOKEN from the template landing-dev. Export that template first, or both together (repeat --repo).");
  });

  it("a failing command stops the export with an English message", async () => {
    const t = await setup();
    await writeFile(join(t.bin, "supabase"), `#!/bin/sh\necho '${MADE_UP_ANON}' >&2\nexit 1\n`);
    process.env.PATH = `${t.bin}${delimiter}${oldPath ?? ""}`;
    expect(await main(["env", "export", "--from-template", "--config", t.config, "--repo", "landing", "--repo", "intake"], t.io)).toBe(2);
    expect(t.err.at(-1)).toBe("Error: Command supabase-status failed (exit code 1). Is the local stack running? (supabase start)");
    expect([...t.out, ...t.err].join("\n")).not.toContain(MADE_UP_ANON);
  });

  it("a required prompt reports the missing keys in English", async () => {
    const t = await setup();
    expect(await main(["env", "export", "--config", t.config, "--repo", "needs", "--out", join(t.dir, "needs.env"), "--from-template"], t.io)).toBe(1);
    expect(t.err).toEqual(["needs: input required for STRIPE_SECRET_KEY. Pass --prompt KEY=VALUE or SECRET_DESK_PROMPT_<KEY>, or mark the entry optional."]);
  });

  it("--out works with one repository only, unknown repositories are named", async () => {
    const t = await setup();
    await expect(main(["env", "export", "--from-template", "--config", t.config, "--repo", "a", "--repo", "b", "--out", "x"], t.io)).resolves.toBe(2);
    expect(t.err.at(-1)).toContain("--out works with a single --repo only.");
    expect(await main(["env", "export", "--from-template", "--config", t.config, "--repo", "nope"], t.io)).toBe(1);
    expect(t.err.at(-1)).toBe("Error: no dev template for nope.");
  });
});

describe.skipIf(process.platform === "win32")("exportEnv: target and commands", () => {
  it("without a linked folder a human writes to <fallbackDir>/<file>; an agent never runs commands", async () => {
    const t = await setup();
    process.env.PATH = `${t.bin}${delimiter}${oldPath ?? ""}`;
    await writeFile(join(t.dir, "links.json"), JSON.stringify({ version: 1, links: {} }));
    const rt = await createRuntime(t.config, { vault: null });
    const fallback = join(t.dir, "cwd");
    const r = await exportEnv(rt, { kind: "human", name: "cli" }, { repo: "landing", fallbackDir: fallback });
    expect(r).toMatchObject({ status: "written", path: join(fallback, "apps", "web", ".env.local") });
    const agentDir = join(t.dir, "agent");
    await mkdir(join(agentDir, "supabase"), { recursive: true });
    await writeFile(join(agentDir, "supabase", "config.toml"), "");
    const a = await exportEnv(rt, { kind: "agent", name: "mcp" }, { repo: "intake", path: join(agentDir, ".env.local"), runCommands: true, runValues: new Map([["landing-dev:LEAD_INTAKE_TOKEN", "abc"]]) });
    if (a.status !== "written") throw new Error("expected written");
    expect(a.skipped).toEqual(["SUPABASE_ANON_KEY", "MAPS_KEY"]);
    expect(await readFile(a.path, "utf8")).not.toContain(MADE_UP_ANON);
  });
});

describe("orderTemplatesByRefs", () => {
  it("puts referenced templates first and survives cycles", () => {
    const a = { id: "a", entries: [{ from: { type: "ref", template: "b" } }] };
    const b = { id: "b", entries: [{ from: { type: "generate" } }] };
    const c = { id: "c", entries: [{ from: { type: "ref", template: "d" } }] };
    const d = { id: "d", entries: [{ from: { type: "ref", template: "c" } }] };
    expect(orderTemplatesByRefs([a, b]).map((t) => t.id)).toEqual(["b", "a"]);
    expect(orderTemplatesByRefs([c, d]).map((t) => t.id).sort()).toEqual(["c", "d"]);
  });
});
