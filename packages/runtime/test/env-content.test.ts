import { mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { PolicyError, createRuntime, exportEnvContent } from "../src/index.js";

// Made-up values, assembled here so nothing secret-looking is a literal.
const TRICKY = ["it's", "$HOME", '"q"'].join(" ");
const STAGING_SECRET = ["staging", "only", "value"].join("-");

const INVENTORY = `version: 1
secrets:
  - { id: api-key-dev, name: API_KEY, stage: dev, service: x, provider: manual, expiry: none, places: [{ repo: acme-app, scope: repository }] }
  - { id: session-dev, name: SESSION_KEY, stage: dev, service: x, provider: manual, expiry: none, places: [{ repo: acme-app, scope: repository }] }
  - { id: ask-dev, name: ASK_KEY, stage: dev, service: x, provider: manual, expiry: none, places: [{ repo: acme-app, scope: repository }] }
  - { id: issue-dev, name: ISSUE_KEY, stage: dev, service: x, provider: manual, expiry: none, places: [{ repo: acme-app, scope: repository }] }
  - { id: lonely-dev, name: LONELY_KEY, stage: dev, service: x, provider: manual, expiry: none, places: [{ repo: acme-app, scope: repository }] }
  - { id: other-dev, name: OTHER_REPO_KEY, stage: dev, service: x, provider: manual, expiry: none, places: [{ repo: acme-docs, scope: repository }] }
  - { id: token-staging, name: TOKEN, stage: staging, service: x, provider: manual, expiry: none, places: [{ repo: acme-app, scope: environment, environment: staging }] }
variables:
  - { id: v-zeta, name: ZETA_URL, stage: dev, value: "http://localhost:3000", places: [{ repo: acme-app, scope: repository }] }
  - { id: v-alpha, name: ALPHA_FLAG, stage: dev, value: ${JSON.stringify(TRICKY)}, places: [{ repo: acme-app, scope: repository }] }
  - { id: v-novalue, name: NO_VALUE, stage: dev, places: [{ repo: acme-app, scope: repository }] }
  - { id: v-staging, name: SITE_URL, stage: staging, value: "https://staging.example.com", places: [{ repo: acme-app, scope: environment, environment: staging }] }
  - { id: v-docs, name: DOCS_ONLY, stage: dev, value: "x", places: [{ repo: acme-docs, scope: repository }] }
  - { id: v-renamed, name: SOURCE_NAME, stage: dev, value: "renamed", places: [{ repo: acme-app, scope: repository, name: TARGET_NAME }] }
  - { id: v-link, name: LINKED, stage: dev, value: "from-variable", places: [{ repo: acme-docs, scope: repository }] }
envTemplates:
  - id: acme-app-dev
    repo: acme-app
    stage: dev
    entries:
      - { key: API_KEY, from: { type: generate, kind: hex, bytes: 16 } }
      - { key: SESSION_KEY, from: { type: variable, variable: v-link } }
      - { key: ASK_KEY, from: { type: prompt } }
      - { key: ISSUE_KEY, from: { type: issue, secret: token-staging } }
      - { key: EXTRA_DEFAULT, from: { type: default, value: "local only" }, description: "Extra" }
`;

async function setup(agentStages = "[dev]") {
  const dir = await mkdtemp(join(tmpdir(), "sd-env-content-"));
  await writeFile(join(dir, "inventory.yaml"), INVENTORY);
  await writeFile(join(dir, "secret-desk.config.yaml"), `inventory: ./inventory.yaml\ngithub:\n  owner: acme\n  auth: { type: pat, source: { type: env, name: GH_TEST } }\npolicy:\n  agentStages: ${agentStages}\n`);
  return createRuntime(join(dir, "secret-desk.config.yaml"), { vault: null, env: { GH_TEST: "x" } as unknown as NodeJS.ProcessEnv, fetch: (async () => new Response(null, { status: 204 })) as unknown as typeof fetch });
}

const agent = { kind: "agent", name: "claude" } as const;
const human = { kind: "human", name: "alice" } as const;
const NOW = new Date("2026-11-05T10:00:00Z");

describe("exportEnvContent: content", () => {
  it("variables only: sorted, quoted, header, missing line, other repos left out", async () => {
    const rt = await setup();
    const r = exportEnvContent(rt, human, { repo: "acme-app", stage: "dev", now: NOW });
    expect(r.filename).toBe(".env.local");
    expect(r.content.split("\n").slice(0, 3)).toEqual([
      "# Generated by secret-desk on 2026-11-05T10:00:00.000Z for acme-app (dev).",
      "# Do not commit this file. Do not share it.",
      "",
    ]);
    const body = r.content.split("\n").slice(3).filter(Boolean);
    expect(body).toEqual([
      // single quotes are impossible around a value with a single quote: double quotes, escaped
      `ALPHA_FLAG="it's \\$HOME \\"q\\""`,
      "# NO_VALUE= (missing: no target value set)",
      "TARGET_NAME=renamed",
      "ZETA_URL=http://localhost:3000",
    ]);
    expect(r.keys).toEqual(["ALPHA_FLAG", "TARGET_NAME", "ZETA_URL"]);
    expect(r.missing).toEqual([{ name: "NO_VALUE", reason: "no target value set" }]);
    expect(r.content).not.toContain("DOCS_ONLY");
  });

  it("wraps harmless-looking but unsafe values in single quotes", async () => {
    const rt = await setup();
    const inv = rt.inventory.data.variables.find((v) => v.id === "v-zeta")!;
    inv.value = "a b$(x)";
    expect(exportEnvContent(rt, human, { repo: "acme-app", stage: "dev", now: NOW }).content).toContain("ZETA_URL='a b$(x)'");
  });

  it("include all: dev secrets with a template value, others as missing lines", async () => {
    const rt = await setup();
    const r = exportEnvContent(rt, agent, { repo: "acme-app", stage: "dev", include: "all", now: NOW });
    const lines = r.content.split("\n");
    const get = (name: string) => lines.find((l) => l.startsWith(`${name}=`));
    expect(get("API_KEY")).toMatch(/^API_KEY=[0-9a-f]{32}$/);
    expect(get("SESSION_KEY")).toBe("SESSION_KEY=from-variable");
    expect(get("EXTRA_DEFAULT")).toBe("EXTRA_DEFAULT='local only'");
    expect(lines).toContain("# Extra");
    expect(lines).toContain("# ASK_KEY= (missing: needs a value from a human)");
    expect(lines).toContain("# ISSUE_KEY= (missing: issued at the provider by the dev environment export, not by this export)");
    expect(lines).toContain("# LONELY_KEY= (missing: no dev value available)");
    expect(r.content).not.toContain("OTHER_REPO_KEY");
    // sorted by name
    const names = lines.filter((l) => /^#? ?[A-Z_]+=/.test(l)).map((l) => l.replace(/^# /, "").split("=")[0]);
    expect(names).toEqual([...names].sort());
    expect(r.missing.map((m) => m.name)).toEqual(["ASK_KEY", "ISSUE_KEY", "LONELY_KEY", "NO_VALUE"]);
  });

  it("json format carries values and missing, same rules", async () => {
    const rt = await setup();
    const r = exportEnvContent(rt, human, { repo: "acme-app", stage: "dev", include: "all", format: "json", now: NOW });
    expect(r.filename).toBe("env.dev.json");
    const j = JSON.parse(r.content) as { values: Record<string, string>; missing: { name: string }[]; stage: string };
    expect(j.stage).toBe("dev");
    expect(j.values.ZETA_URL).toBe("http://localhost:3000");
    expect(j.values.API_KEY).toMatch(/^[0-9a-f]{32}$/);
    expect(j.missing.map((m) => m.name)).toContain("ASK_KEY");
  });

  it("a comment cannot smuggle an assignment (line breaks in a description)", async () => {
    const rt = await setup();
    rt.inventory.data.variables.find((v) => v.id === "v-zeta")!.description = `harmless\nEVIL=1`;
    const r = exportEnvContent(rt, human, { repo: "acme-app", stage: "dev", now: NOW });
    expect(r.content.split("\n")).not.toContain("EVIL=1");
  });
});

describe("exportEnvContent: policy matrix", () => {
  it("agent: dev ok", async () => {
    const rt = await setup();
    expect(() => exportEnvContent(rt, agent, { repo: "acme-app", stage: "dev" })).not.toThrow();
  });
  it("agent: staging denied, also when the policy names it only as a non-dev stage", async () => {
    const rt = await setup();
    expect(() => exportEnvContent(rt, agent, { repo: "acme-app", stage: "staging" })).toThrow(PolicyError);
    expect(() => exportEnvContent(rt, agent, { repo: "acme-app", stage: "production" })).toThrow(PolicyError);
    const rt2 = await setup("[dev, production]");
    expect(() => exportEnvContent(rt2, agent, { repo: "acme-app", stage: "production" })).toThrow(PolicyError);
  });
  it("agent: unknown stage is a plain error", async () => {
    const rt = await setup();
    expect(() => exportEnvContent(rt, agent, { repo: "acme-app", stage: "nope" })).toThrow(/Unbekannte Stage/);
  });
  it("human: variables of any stage", async () => {
    const rt = await setup();
    const r = exportEnvContent(rt, human, { repo: "acme-app", stage: "staging" });
    expect(r.content).toContain("SITE_URL=https://staging.example.com");
    expect(r.filename).toBe(".env.staging");
  });
  it("human: secrets of a non-dev stage are omitted, never exported, even if a template names the key", async () => {
    const rt = await setup();
    rt.inventory.data.envTemplates.push({ id: "sneaky", repo: "acme-app", stage: "staging", file: ".env", entries: [{ key: "TOKEN", from: { type: "default", value: STAGING_SECRET } }] });
    const r = exportEnvContent(rt, human, { repo: "acme-app", stage: "staging", include: "all" });
    expect(r.content).toContain("# TOKEN= (missing: secret values of stage staging are never exported)");
    expect(r.content).not.toContain(STAGING_SECRET);
    expect(r.keys).toEqual(["SITE_URL"]);
  });
  it("the dev export never carries a staging value (issue source is not issued)", async () => {
    const rt = await setup();
    const r = exportEnvContent(rt, agent, { repo: "acme-app", stage: "dev", include: "all" });
    expect(r.content).not.toContain("staging.example.com");
  });
});
