const exact = new Map<string, string>(EXACT_ENTRIES);

function applyTemplate(template: string, groups: string[], depth: number): string {
  return template.replace(/\$(\d)/g, (_m, d: string) => {
    const g = groups[Number(d) - 1] ?? "";
    return translate(g, depth + 1);
  });
}

function translate(text: string, depth: number): string {
  if (depth > 4 || text === "") return text;
  const hit = exact.get(text);
  if (hit !== undefined) return hit;

  for (const [re, tpl] of PATTERN_ENTRIES) {
    const m = re.exec(text);
    if (!m) continue;
    const out = applyTemplate(tpl, m.slice(1), depth);
    return /\s$/.test(text) || !/\s$/.test(out) ? out : out.replace(/\s+$/, "");
  }

  // Zusammengesetzte Texte: Listen und "Kopf: Rest".
  for (const sep of ["\n", "   ", "; "]) {
    if (text.includes(sep)) {
      const parts = text.split(sep).map((p) => translate(p, depth + 1));
      const joined = parts.join(sep);
      if (joined !== text) return joined;
    }
  }
  const colon = /^([^\s:]+(?:\.[^\s:]+)*): ([\s\S]+)$/.exec(text);
  if (colon) {
    const rest = translate(colon[2]!, depth + 1);
    if (rest !== colon[2]) return `${colon[1]}: ${rest}`;
  }
  return text;
}

/** Deutschen Backend-Text ins Englische uebersetzen; unbekannte Texte bleiben unveraendert. */
export function translateEn(text: string): string {
  return translate(text, 0);
}

/** Alle Strings in JSON-aehnlichen Werten uebersetzen (Schluessel bleiben). "de" liefert den Wert unveraendert. */
export function translateDeep<T>(value: T, locale: "de" | "en"): T {
  if (locale !== "en") return value;
  return walk(value) as T;
}

function walk(v: unknown): unknown {
  if (typeof v === "string") return translateEn(v);
  if (Array.isArray(v)) return v.map(walk);
  if (v !== null && typeof v === "object") {
    const proto = Object.getPrototypeOf(v);
    if (proto !== Object.prototype && proto !== null) return v;
    const out: Record<string, unknown> = {};
    for (const [k, val] of Object.entries(v as Record<string, unknown>)) out[k] = walk(val);
    return out;
  }
  return v;
}
