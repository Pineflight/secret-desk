import { EnvExportError, agentStageIds, commentText, findStage, formatEnvValue, generateEntryValue, stageKind, type EnvSource } from "@secret-desk/core";
import { PolicyError, type Actor } from "./agent-api.js";
import type { Runtime } from "./runtime.js";

export type EnvExportFormat = "dotenv" | "json";
export type EnvExportInclude = "variables" | "all";

export interface EnvExportInput {
  repo: string;
  stage: string;
  format?: EnvExportFormat;
  include?: EnvExportInclude;
  /** Test hook: fixed clock for the header line. */
  now?: Date;
}

export interface EnvExportMissing {
  name: string;
  reason: string;
}

export interface EnvExportResult {
  repo: string;
  stage: string;
  format: EnvExportFormat;
  include: EnvExportInclude;
  /** Suggested file name for a download or a write. */
  filename: string;
  /** The file content. It holds values: never log it, never put it on screen. */
  content: string;
  /** Names that carry a value in the content (no values). */
  keys: string[];
  /** Names listed without a value, with the reason. */
  missing: EnvExportMissing[];
}

interface Line {
  name: string;
  /** null = no value available. */
  value: string | null;
  reason: string;
  note: string | undefined;
}

const NON_DEV_SECRET = (stage: string): string => `secret values of stage ${stage} are never exported`;

function dotenvText(lines: Line[], repo: string, stage: string, now: Date): string {
  const out = [
    `# Generated by secret-desk on ${now.toISOString()} for ${commentText(repo)} (${commentText(stage)}).`,
    "# Do not commit this file. Do not share it.",
    "",
  ];
  for (const l of lines) {
    if (l.note) out.push(`# ${commentText(l.note)}`);
    out.push(l.value === null ? `# ${l.name}= (missing: ${commentText(l.reason)})` : `${l.name}=${formatEnvValue(l.value)}`);
  }
  return `${out.join("\n")}\n`;
}

/** Template value for one env entry of the dev stage, or the reason there is none. */
function templateValue(rt: Runtime, from: EnvSource, pairs: Map<string, { publicKey: string; privateKey: string }>): { value: string } | { reason: string } {
  switch (from.type) {
    case "default":
      return { value: from.value };
    case "generate":
      return { value: generateEntryValue(from, pairs) };
    case "variable": {
      const v = rt.inventory.getVariable(from.variable);
      return v && v.value !== null ? { value: v.value } : { reason: `variable ${from.variable} has no target value` };
    }
    case "issue":
      return { reason: "issued at the provider by the dev environment export, not by this export" };
    case "prompt":
      return { reason: from.optional ? "optional, needs a value from a human" : "needs a value from a human" };
    case "ref":
      return { reason: `value of ${from.key} in template ${from.template}, filled by the template export` };
    case "command":
      return { reason: `read from ${from.command} by the CLI template export on the developer machine` };
  }
}

/**
 * One export for a repository and a stage: every variable and (when `include` is "all") every secret that has a place in
 * the repository, plus the template keys of a dev stage. Nothing is written and nothing is issued.
 *
 * Secret values are never stored. A secret gets a value only on a stage of kind dev, only when a dev template of the
 * repository supplies one (default, generated or variable source). Everything else is listed as a commented
 * `# NAME= (missing: reason)` line, so the file shows what is missing without leaking anything.
 *
 * Policy: an agent may export only the stages of `policy.agentStages`. A human may export any stage, but secret values of
 * a stage that is not of kind dev are never exported, for nobody.
 */
export function exportEnvContent(rt: Runtime, actor: Actor, input: EnvExportInput): EnvExportResult {
  const format = input.format ?? "dotenv";
  const include = input.include ?? "variables";
  const stages = rt.inventory.stages;
  if (!findStage(stages, input.stage)) throw new EnvExportError(`Unbekannte Stage: ${input.stage}`);
  if (actor.kind === "agent" && !agentStageIds(rt.config, stages).includes(input.stage)) {
    throw new PolicyError(`Agenten duerfen fuer ${input.stage} keine .env exportieren.`);
  }
  const isDev = stageKind(stages, input.stage) === "dev";
  const data = rt.inventory.data;
  const lines = new Map<string, Line>();
  const put = (l: Line): void => {
    if (!lines.has(l.name)) lines.set(l.name, l);
  };

  const templates = isDev ? data.envTemplates.filter((t) => t.repo === input.repo && t.stage === input.stage) : [];
  const pairs = new Map<string, { publicKey: string; privateKey: string }>();
  const templateByKey = new Map<string, { from: EnvSource; description: string | undefined }>();
  for (const t of templates) for (const e of t.entries) if (!templateByKey.has(e.key)) templateByKey.set(e.key, { from: e.from, description: e.description });

  for (const v of data.variables) {
    if (v.stage !== input.stage) continue;
    for (const p of v.places) {
      if (p.repo !== input.repo) continue;
      put({ name: p.name ?? v.name, value: v.value, reason: "no target value set", note: v.description });
    }
  }
  if (include === "all") {
    for (const s of data.secrets) {
      if (s.stage !== input.stage) continue;
      for (const p of s.places) {
        if (p.scope === "cloudflare-worker" || p.repo !== input.repo) continue;
        const name = p.name ?? s.name;
        if (!isDev) {
          put({ name, value: null, reason: NON_DEV_SECRET(input.stage), note: s.description });
          continue;
        }
        const t = templateByKey.get(name);
        const r = t ? templateValue(rt, t.from, pairs) : { reason: "no dev value available" };
        put("value" in r ? { name, value: r.value, reason: "", note: s.description } : { name, value: null, reason: r.reason, note: s.description });
      }
    }
    // Template keys that no inventory entry names (typical for a dev stage without places).
    for (const [key, t] of templateByKey) {
      const r = templateValue(rt, t.from, pairs);
      put("value" in r ? { name: key, value: r.value, reason: "", note: t.description } : { name: key, value: null, reason: r.reason, note: t.description });
    }
  }

  const sorted = [...lines.values()].sort((a, b) => (a.name < b.name ? -1 : 1));
  const now = input.now ?? new Date();
  const missing = sorted.filter((l) => l.value === null).map((l) => ({ name: l.name, reason: l.reason }));
  const content =
    format === "dotenv"
      ? dotenvText(sorted, input.repo, input.stage, now)
      : `${JSON.stringify(
          {
            repo: input.repo,
            stage: input.stage,
            generatedAt: now.toISOString(),
            note: "Do not commit this file. Do not share it.",
            values: Object.fromEntries(sorted.filter((l) => l.value !== null).map((l) => [l.name, l.value])),
            missing,
          },
          null,
          2,
        )}\n`;
  return {
    repo: input.repo,
    stage: input.stage,
    format,
    include,
    filename: format === "json" ? `env.${input.stage}.json` : isDev ? ".env.local" : `.env.${input.stage}`,
    content,
    keys: sorted.filter((l) => l.value !== null).map((l) => l.name),
    missing,
  };
}
