const INVENTORY = `version: 1
secrets:
  - id: cf-dev-token
    name: CLOUDFLARE_API_TOKEN
    stage: dev
    service: cloudflare
    provider: fake-issuer
    expiry: none
    places: []
envTemplates:
  - id: portal-dev
    repo: portal
    stage: dev
    entries:
      - { key: SITE_URL, from: { type: default, value: "http://localhost:3000" } }
      - { key: WEBHOOK_SECRET, from: { type: generate, kind: base64url, bytes: 24, prefix: whsec_ } }
      - { key: VAPID_PUBLIC_KEY, from: { type: generate, kind: vapid-public } }
      - { key: VAPID_PRIVATE_KEY, from: { type: generate, kind: vapid-private } }
      - { key: MAPS_KEY, description: "Only needed for the map view", from: { type: prompt, optional: true, hint: "from the maps console" } }
      - { key: SUPABASE_ANON_KEY, from: { type: command, command: supabase-status, key: ANON_KEY } }
      - { key: SUPABASE_EXTRA, from: { type: command, command: supabase-status, key: NOT_THERE, optional: true } }
  - id: landing-dev
    repo: landing
    stage: dev
    entries:
      - { key: LEAD_INTAKE_TOKEN, from: { type: generate, kind: hex, bytes: 16 } }
  - id: intake-dev
    repo: intake
    stage: dev
    entries:
      - { key: CF_TOKEN, from: { type: issue, secret: cf-dev-token } }
      - { key: LEAD_INTAKE_TOKENS, from: { type: ref, template: landing-dev, key: LEAD_INTAKE_TOKEN } }
`;

const MADE_UP_ANON = ["made", "up", "anon", "value"].join("-");

function setup() {
  const inventory = InventoryStore.fromText(INVENTORY);
  const issued: string[] = [];
  const revoked: string[] = [];
  const providers = new ProviderRegistry().register({
    id: "fake-issuer",
    label: "Fake",
    kind: "automatic",
    issue: async () => {
      issued.push("x");
      return { value: new SecretValue(["issued", "dev", "token"].join("-")), externalId: "ext-1" };
    },
    revoke: async () => {
      revoked.push("ext-1");
    },
  });
  const base = { inventory, providers, connections: new ConnectionStore() };
  const tpl = (id: string) => inventory.data.envTemplates.find((t) => t.id === id)!;
  return { inventory, base, tpl, issued, revoked };
}

const supabaseOutput = async () => new Map([["ANON_KEY", MADE_UP_ANON], ["API_URL", "http://127.0.0.1:54321"]]);

describe("dev template sources", () => {
  it("writes an English header", async () => {
    const { base, tpl } = setup();
    const r = await buildEnvFile(tpl("landing-dev"), base);
    expect(r.text.split("\n")[0]).toMatch(/^# Generated by secret-desk on \d{4}-\d{2}-\d{2} for landing \(dev\)\.$/);
    expect(r.text).toContain("# Contains secrets. Do not commit, do not share.");
  });

  it("optional prompt without input: commented empty line, no PromptsRequiredError", async () => {
    const { base, tpl } = setup();
    const r = await buildEnvFile(tpl("portal-dev"), { ...base, runCommand: supabaseOutput });
    expect(r.text).toContain("# Only needed for the map view\n# MAPS_KEY= (optional: from the maps console)\n");
    expect(r.text).not.toMatch(/^MAPS_KEY=/m);
    expect(r.skipped).toContain("MAPS_KEY");
    expect(r.sources.MAPS_KEY).toBe("prompt");
  });

  it("optional prompt with input is written", async () => {
    const { base, tpl } = setup();
    const r = await buildEnvFile(tpl("portal-dev"), { ...base, runCommand: supabaseOutput, prompts: { MAPS_KEY: "typed-value" } });
    expect(r.text).toContain("MAPS_KEY=typed-value\n");
    expect(r.skipped).not.toContain("MAPS_KEY");
  });

  it("a required prompt still blocks", async () => {
    const inventory = InventoryStore.fromText(INVENTORY.replace("{ type: prompt, optional: true, hint: \"from the maps console\" }", "{ type: prompt }"));
    const t = inventory.data.envTemplates[0]!;
    await expect(buildEnvFile(t, { inventory, providers: new ProviderRegistry(), connections: new ConnectionStore() })).rejects.toThrow(PromptsRequiredError);
  });

  it("generate: prefix, base64url and a matching VAPID pair", async () => {
    const { base, tpl } = setup();
    const r = await buildEnvFile(tpl("portal-dev"), { ...base, runCommand: supabaseOutput });
    const env = parseEnvText(r.text);
    expect(env.get("WEBHOOK_SECRET")).toMatch(/^whsec_[A-Za-z0-9_-]{32}$/);
    const pub = env.get("VAPID_PUBLIC_KEY")!;
    const priv = env.get("VAPID_PRIVATE_KEY")!;
    expect(Buffer.from(pub, "base64url")).toHaveLength(65);
    expect(Buffer.from(priv, "base64url")).toHaveLength(32);
    const ecdh = createECDH("prime256v1");
    ecdh.setPrivateKey(Buffer.from(priv, "base64url"));
    expect(ecdh.getPublicKey().toString("base64url")).toBe(pub);
  });

  it("command: value from the runner, run once per command, optional missing key left empty", async () => {
    const { base, tpl } = setup();
    let calls = 0;
    const r = await buildEnvFile(tpl("portal-dev"), { ...base, runCommand: async (c) => { calls++; return supabaseOutput(); } });
    expect(calls).toBe(1);
    expect(r.text).toContain(`SUPABASE_ANON_KEY=${MADE_UP_ANON}\n`);
    expect(r.text).toContain("# SUPABASE_EXTRA= (optional, not reported by supabase-status)");
    expect(r.sources.SUPABASE_ANON_KEY).toBe("command");
    expect(JSON.stringify({ ...r, text: undefined })).not.toContain(MADE_UP_ANON);
  });

  it("command without a runner (portal, agents): commented line, nothing runs", async () => {
    const { base, tpl } = setup();
    const r = await buildEnvFile(tpl("portal-dev"), base);
    expect(r.text).toContain("# SUPABASE_ANON_KEY= (filled by the CLI from supabase-status)");
    expect(r.skipped).toEqual(expect.arrayContaining(["SUPABASE_ANON_KEY", "SUPABASE_EXTRA"]));
  });

  it("command: a missing required key fails without the command output in the message", async () => {
    const { base, tpl } = setup();
    const err = await buildEnvFile(tpl("portal-dev"), { ...base, runCommand: async () => new Map([["API_URL", MADE_UP_ANON]]) }).catch((e: Error) => e);
    expect(err).toBeInstanceOf(Error);
    expect((err as Error).message).toMatch(/SUPABASE_ANON_KEY: Befehl supabase-status liefert keinen Wert fuer ANON_KEY/);
    expect((err as Error).message).not.toContain(MADE_UP_ANON);
  });

  it("ref: shares one generated value within a run", async () => {
    const { base, tpl } = setup();
    const runValues = new Map<string, string>();
    const landing = await buildEnvFile(tpl("landing-dev"), { ...base, runValues });
    const intake = await buildEnvFile(tpl("intake-dev"), { ...base, runValues });
    const token = parseEnvText(landing.text).get("LEAD_INTAKE_TOKEN");
    expect(token).toMatch(/^[0-9a-f]{32}$/);
    expect(parseEnvText(intake.text).get("LEAD_INTAKE_TOKENS")).toBe(token);
    expect(intake.sources.LEAD_INTAKE_TOKENS).toBe("ref");
    expect(JSON.stringify({ ...intake, text: undefined })).not.toContain(token!);
  });

  it("ref: reads the file the other template produced", async () => {
    const { base, tpl } = setup();
    const produced = "# header\nLEAD_INTAKE_TOKEN='abc def'\n";
    const r = await buildEnvFile(tpl("intake-dev"), { ...base, readTemplateFile: async (t) => (t.id === "landing-dev" ? produced : null) });
    expect(r.text).toContain("LEAD_INTAKE_TOKENS='abc def'\n");
  });

  it("ref: a template already exported in this run never falls back to its old file", async () => {
    const inventory = InventoryStore.fromText(INVENTORY.replace("{ key: LEAD_INTAKE_TOKEN, from: { type: generate, kind: hex, bytes: 16 } }", "{ key: LEAD_INTAKE_TOKEN, from: { type: prompt, optional: true } }"));
    const base = { inventory, providers: new ProviderRegistry().register({ id: "fake-issuer", label: "F", kind: "automatic", issue: async () => ({ value: new SecretValue("v") }) }), connections: new ConnectionStore() };
    const tpl = (id: string) => inventory.data.envTemplates.find((t) => t.id === id)!;
    const runValues = new Map<string, string>();
    await buildEnvFile(tpl("landing-dev"), { ...base, runValues });
    const stale = "LEAD_INTAKE_TOKEN=old-value\n";
    await expect(buildEnvFile(tpl("intake-dev"), { ...base, runValues, readTemplateFile: async () => stale })).rejects.toThrow(/Kein Wert fuer LEAD_INTAKE_TOKEN/);
  });

  it("ref: no value anywhere fails before anything is issued", async () => {
    const { base, tpl, issued } = setup();
    await expect(buildEnvFile(tpl("intake-dev"), { ...base, readTemplateFile: async () => null })).rejects.toThrow(/LEAD_INTAKE_TOKENS: Kein Wert fuer LEAD_INTAKE_TOKEN aus der Vorlage landing-dev/);
    expect(issued).toEqual([]);
  });
});

describe("template schema for ref and generate", () => {
  it("rejects unknown templates, unknown keys, ref to ref and a VAPID prefix", () => {
    const bad = (entry: string, extra = "") =>
      () => InventoryStore.fromText(`version: 1\nsecrets: []\nenvTemplates:\n  - id: a\n    repo: a\n    entries:\n      - { key: X, from: { type: generate } }\n      - ${entry}\n${extra}`);
    expect(bad("{ key: Y, from: { type: ref, template: nope, key: X } }")).toThrow(/unbekannte Vorlage: nope/);
    expect(bad("{ key: Y, from: { type: ref, template: a, key: X } }")).toThrow(/eigene Vorlage/);
    expect(bad("{ key: Y, from: { type: ref, template: b, key: Q } }", "  - id: b\n    repo: b\n    entries:\n      - { key: Z, from: { type: generate } }\n")).toThrow(/unbekannter Schluessel in b: Q/);
    expect(bad("{ key: Y, from: { type: ref, template: b, key: Z } }", "  - id: b\n    repo: b\n    entries:\n      - { key: Z, from: { type: ref, template: a, key: X } }\n")).toThrow(/ref auf einen ref-Eintrag/);
    expect(bad("{ key: Y, from: { type: generate, kind: vapid-public, prefix: x_ } }")).toThrow(/VAPID/);
    expect(bad("{ key: Y, from: { type: ref, template: b, key: Z } }", "  - id: b\n    repo: b\n    stage: staging\n    entries:\n      - { key: Z, from: { type: generate } }\n")).toThrow(/ref nur innerhalb derselben Stage: b ist staging/);
    expect(bad("{ key: Y, from: { type: command, command: rm-rf, key: X } }")).toThrow();
  });
});

describe("parseEnvText", () => {
  it("reads back what formatEnvValue writes", () => {
    const values = ["plain-1.2", "a b", "it's $HOME `x`", "line1\nline2", "back\\slash", "q\"uote", ""];
    const text = values.map((v, i) => `K${i}=${formatEnvValue(v)}`).join("\n");
    const parsed = parseEnvText(`# comment\n\n${text}\n`);
    values.forEach((v, i) => expect(parsed.get(`K${i}`)).toBe(v));
  });
  it("keeps a carriage return inside quotes and skips an unterminated quote without losing later keys", () => {
    expect(parseEnvText(formatEnvValue("a\rb").replace(/^/, "K=")).get("K")).toBe("a\rb");
    const parsed = parseEnvText("A='never closed\nB=after\r\n");
    expect(parsed.has("A")).toBe(false);
    expect(parsed.get("B")).toBe("after");
  });
  it("accepts export prefixes, double quotes and inline comments", () => {
    const parsed = parseEnvText('export A="x y"\nB=plain # note\n# C=hidden\n');
    expect(parsed.get("A")).toBe("x y");
    expect(parsed.get("B")).toBe("plain");
    expect(parsed.has("C")).toBe(false);
  });
});

describe.skipIf(process.platform === "win32")("runEnvCommand", () => {
  async function fakeSupabase(script: string): Promise<string> {
    const dir = await mkdtemp(join(tmpdir(), "sd-bin-"));
    const file = join(dir, "supabase");
    await writeFile(file, `#!/bin/sh\n${script}\n`);
    await chmod(file, 0o755);
    return dir;
  }
  async function withPath<T>(dir: string, fn: () => Promise<T>): Promise<T> {
    const old = process.env.PATH;
    process.env.PATH = `${dir}${delimiter}${old ?? ""}`;
    try {
      return await fn();
    } finally {
      process.env.PATH = old;
    }
  }
  it("runs the fixed program and parses its env output", async () => {
    const bin = await fakeSupabase(`[ "$1 $2 $3" = "status -o env" ] || exit 9\necho 'ANON_KEY="${MADE_UP_ANON}"'`);
    const out = await withPath(bin, () => runEnvCommand("supabase-status", tmpdir()));
    expect(out.get("ANON_KEY")).toBe(MADE_UP_ANON);
  });
  it("the command sees no prompt values or other tokens from the environment", async () => {
    const bin = await fakeSupabase(`[ -z "$SECRET_DESK_PROMPT_LEAK_TEST" ] || exit 4\necho 'API_URL=ok'`);
    process.env.SECRET_DESK_PROMPT_LEAK_TEST = "made-up";
    try {
      expect((await withPath(bin, () => runEnvCommand("supabase-status", tmpdir()))).get("API_URL")).toBe("ok");
    } finally {
      delete process.env.SECRET_DESK_PROMPT_LEAK_TEST;
    }
  });
  it("a failing command names only the exit code, never its output", async () => {
    const bin = await fakeSupabase(`echo 'ANON_KEY=${MADE_UP_ANON}'\necho '${MADE_UP_ANON}' >&2\nexit 3`);
    const err = await withPath(bin, () => runEnvCommand("supabase-status", tmpdir())).catch((e: Error) => e);
    expect((err as Error).message).toBe("Befehl supabase-status fehlgeschlagen (Exit-Code 3). Laeuft der lokale Stack? Im Repository starten mit: supabase start");
  });
  it("prefers the repository's own binary and names the repository's start script", async () => {
    const repo = await mkdtemp(join(tmpdir(), "sd-repo-"));
    await mkdir(join(repo, "node_modules", ".bin"), { recursive: true });
    const local = join(repo, "node_modules", ".bin", "supabase");
    await writeFile(local, `#!/bin/sh\necho 'API_URL=http://127.0.0.1:54321'\n`);
    await chmod(local, 0o755);
    const globalBin = await fakeSupabase("exit 5");
    expect((await withPath(globalBin, () => runEnvCommand("supabase-status", repo))).get("API_URL")).toBe("http://127.0.0.1:54321");
    await writeFile(local, "#!/bin/sh\nexit 1\n");
    await writeFile(join(repo, "pnpm-lock.yaml"), "");
    expect(supabaseStartCommand(repo)).toBe("pnpm exec supabase start");
    await writeFile(join(repo, "package.json"), JSON.stringify({ scripts: { dev: "next dev", "db:start": "supabase start --ignore-health-check" } }));
    expect(supabaseStartCommand(repo)).toBe("pnpm run db:start");
    const err = await runEnvCommand("supabase-status", repo).catch((e: Error) => e);
    expect((err as Error).message).toBe("Befehl supabase-status fehlgeschlagen (Exit-Code 1). Laeuft der lokale Stack? Im Repository starten mit: pnpm run db:start");
  });
});
