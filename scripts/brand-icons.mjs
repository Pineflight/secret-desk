#!/usr/bin/env node
// Writes apps/desk/src/lib/brand-icons.generated.ts: only the logos the vendor catalog uses, taken from the
// `simple-icons` package (CC0-1.0). The page bundles these few paths; nothing is fetched at runtime and no image host is needed.
//   node scripts/brand-icons.mjs           write
//   node scripts/brand-icons.mjs --check   write nothing, exit 1 when the file is stale
// Needs `pnpm run build:libs` first (the catalog is read from the built core package).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { VENDORS } = await import(pathToFileURL(join(root, "packages/core/dist/index.js")).href);
const simple = await import(pathToFileURL(join(root, "apps/desk/node_modules/simple-icons/index.mjs")).href);
const all = Object.values(simple).filter((x) => x && typeof x === "object" && typeof x.slug === "string");

// Marks that simple-icons does not carry live by hand in brand-icons.custom.ts and are skipped here.
const customText = readFileSync(join(root, "apps/desk/src/lib/brand-icons.custom.ts"), "utf8");
const isCustom = (slug) => new RegExp(`^  ${slug}: \\{ title:`, "m").test(customText);
const slugs = [...new Set(VENDORS.map((v) => v.icon).filter(Boolean))].filter((slug) => !isCustom(slug)).sort();
const lines = slugs.map((slug) => {
  const icon = all.find((x) => x.slug === slug);
  if (!icon) throw new Error(`simple-icons has no icon "${slug}": set icon to null for that vendor or add the mark to brand-icons.custom.ts.`);
  return `  ${JSON.stringify(slug)}: { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(icon.path)} },`;
});
const text = `// Generated by scripts/brand-icons.mjs from the simple-icons package (CC0-1.0). Do not edit by hand.
// The logos are trademarks of their owners; they only mark the provider an integration belongs to.
export interface BrandIcon {
  title: string;
  /** Brand color without "#". */
  hex: string;
  /** SVG path on a 24 x 24 grid. */
  path: string;
}

export const BRAND_ICONS: Record<string, BrandIcon> = {
${lines.join("\n")}
};
`;
const file = join(root, "apps/desk/src/lib/brand-icons.generated.ts");
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(file, "utf8"); } catch { /* missing */ }
  if (current !== text) { console.error('FEHLER: brand-icons.generated.ts is stale. Run "node scripts/brand-icons.mjs".'); process.exit(1); }
  process.exit(0);
}
writeFileSync(file, text);
console.log(`${slugs.length} icons written`);
